test('shared speed confirms across peers, survives reconnect, and keeps pause and step authoritative', async ({ page, browser, baseURL }) => {
  const before = await canonicalState(page);
  expect((await page.request.post('/api/saves/upload?expectedWorldEpoch=' + before.worldEpoch,
    { data: readFileSync('../prototype/protocol/saves/mixed-v9.json') })).ok()).toBe(true);
  const context = await browser.newContext({ baseURL });
  const peer = await context.newPage();
  try {
    await page.goto('/'); await ready(page); await peer.goto('/'); await ready(peer);
    const speed = page.getByRole('combobox', { name: 'Game speed', exact: true });
    await expect(page.getByTestId('current-funds')).toHaveText('¥7,000,000,000');
    await expect(speed).toHaveValue('1');
    const paused = await canonicalState(page);
    await speed.selectOption('0.125');
    await expect(speed).toBeEnabled();
    await expect(peer.getByLabel('Game speed', { exact: true })).toHaveValue('0.125');
    expect((await canonicalState(page)).tick).toBe(paused.tick);
    await page.reload(); await ready(page); await expect(speed).toHaveValue('0.125');
    await page.getByRole('button', { name: 'Run', exact: false }).click();
    await expect.poll(async () => BigInt((await canonicalState(page)).tick) > BigInt(paused.tick)).toBe(true);
    await page.getByRole('button', { name: 'Pause', exact: false }).click();
    await expect(peer.getByTestId('clock-state')).toHaveText('Paused');
    const stopped = await canonicalState(page);
    await page.getByRole('button', { name: 'Single step', exact: false }).first().click();
    await expect.poll(async () => (await canonicalState(page)).tick).toBe(String(BigInt(stopped.tick) + 1n));
    await expect(page.getByTestId('clock-state')).toHaveText('Paused');
    await speed.selectOption('2');
    await expect(peer.getByLabel('Game speed', { exact: true })).toHaveValue('2');
  } finally { await context.close(); }
});

test('speed and funds stay reachable in English and Japanese at narrow widths, with role restrictions', async ({ page }, testInfo) => {
  const before = await canonicalState(page);
  expect((await page.request.post('/api/saves/upload?expectedWorldEpoch=' + before.worldEpoch,
    { data: readFileSync('../prototype/protocol/saves/mixed-v9.json') })).ok()).toBe(true);
  await page.goto('/'); await ready(page);
  for (const locale of ['en', 'ja'] as const) {
    if (locale === 'ja') {
      await openPanel(page, 'settings');
      await page.getByLabel('Language', { exact: true }).selectOption('ja');
    }
    const speed = page.getByLabel(locale === 'ja' ? 'ゲーム速度' : 'Game speed', { exact: true });
    for (const width of [320, 390, 768, 1280]) {
      await page.setViewportSize({ width, height: 800 });
      await expect(speed).toBeVisible(); await expect(page.getByTestId('current-funds')).toBeVisible();
      await expect(page.getByTestId('current-funds')).toHaveText('¥7,000,000,000');
      expect(await page.getByTestId('current-funds').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
      const bounds = await fit(page);
      for (const element of [speed, page.getByTestId('current-funds')]) {
        const rect = await element.boundingBox(); expect(rect).not.toBeNull();
        expect(rect!.x).toBeGreaterThanOrEqual(0); expect(rect!.x + rect!.width).toBeLessThanOrEqual(bounds.width);
      }
      if (width === 320) await page.screenshot({ path: testInfo.outputPath(`toolbar-${locale}-320.png`) });
    }
  }
  await openPanel(page, 'session', 'ja');
  await page.getByRole('button', { name: 'ゲームから退出', exact: true }).click();
  await page.getByLabel('アクセスキーを入力してゲームに参加', { exact: true }).fill('operator-test');
  await page.getByRole('button', { name: '接続', exact: true }).click(); await ready(page, 'ja');
  await expect(page.getByLabel('ゲーム速度', { exact: true })).toBeDisabled();
});

// Generated by FleetMovementTests' gameplay-built ring, including its junction.
// An optional save allows the same regression to run against a larger local world.
test('Normal and Fast keep moving trains responsive without resync or disabled-button flicker', async ({page}, testInfo) => {
  const input=process.env.FREETRAIN_CLOCK_REGRESSION_WORLD ?? 'tests/helpers/moving-fleet-v9.json';
  const before=await canonicalState(page);
  expect((await page.request.post('/api/saves/upload?expectedWorldEpoch='+before.worldEpoch,{data:readFileSync(input)})).ok()).toBe(true);
  const messages:Record<string,number>={},sent:Record<string,number>={};
  let lastMoves=0;
  await page.routeWebSocket('**/api/session?*',route=>{
    const server=route.connectToServer();
    server.onMessage(message=>{
      const raw=JSON.parse(String(message));messages[raw.type]=(messages[raw.type]??0)+1;
      if(raw.type==='delta')lastMoves=raw.mixed.fleet.trains[0].moveCount;
      route.send(message);
    });
    route.onMessage(message=>{const raw=JSON.parse(String(message));sent[raw.type]=(sent[raw.type]??0)+1;server.send(message);});
  });
  await page.goto('/');await ready(page);
  const speed=page.getByLabel('Game speed',{exact:true});
  const pause=page.getByRole('button',{name:'Pause',exact:false}).first();
  await page.getByRole('button',{name:'Run',exact:false}).first().click();
  await expect(pause).toBeEnabled();await expect(speed).toBeEnabled();
  const initialTransfers=(messages.stateChunk??0)+(messages.snapshot??0);
  const samples=[];
  for(const rate of ['1','2']) {
    if(rate==='2'){await speed.selectOption(rate);await expect(speed).toBeEnabled();await expect(speed).toHaveValue(rate);}
    const moves=lastMoves,publications=messages.delta??0;
    await page.evaluate(()=>{
      const w=window as any;w.clockDelays=[];w.clockDisabled=0;let last=performance.now();
      w.clockTimer=setInterval(()=>{const now=performance.now();w.clockDelays.push(now-last);last=now;},50);
      w.clockObserver=new MutationObserver(records=>{for(const r of records)if((r.target as HTMLButtonElement).disabled)w.clockDisabled++;});
      for(const el of document.querySelectorAll('.game-speed,.transport button:first-child'))w.clockObserver.observe(el,{attributes:true,attributeFilter:['disabled']});
    });
    // Menus must respond while movement publications keep arriving.
    await openPanel(page,'settings');await expect(page.getByRole('heading',{name:'Settings',exact:true})).toBeVisible();
    await page.evaluate(()=>new Promise(resolve=>setTimeout(resolve,3000)));
    const sample=await page.evaluate(()=>{
      const w=window as any;clearInterval(w.clockTimer);w.clockObserver.disconnect();
      const a=w.clockDelays.sort((a:number,b:number)=>a-b);
      return {p95:a[Math.floor(a.length*.95)],max:a.at(-1),disabled:w.clockDisabled,samples:a.length};
    });
    samples.push({rate,...sample});
    expect(sample.disabled).toBe(0);expect(sample.samples).toBeGreaterThan(15);
    expect(sample.p95).toBeLessThan(200);
    expect(lastMoves).toBeGreaterThan(moves);expect((messages.delta??0)-publications).toBeGreaterThan(10);
    expect(sent.resync??0).toBe(0);
    expect((messages.stateChunk??0)+(messages.snapshot??0)).toBe(initialTransfers);
  }
  await pause.click();await expect(page.getByTestId('clock-state')).toHaveText('Paused');
  await testInfo.attach('running-clock-responsiveness.json',{body:JSON.stringify({samples,messages,sent},null,2),contentType:'application/json'});
});
